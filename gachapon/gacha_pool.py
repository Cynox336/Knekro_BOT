# -- Catálogo y Búsqueda --
def get_all_items_catalog(custom_prizes: list = None):
    catalog = [PROMOTIONAL_5STAR] + list(STANDARD_5STARS) + list(FOUR_STARS)
    if custom_prizes:
        for cp in custom_prizes:
            catalog.append({
                "name": f"✨ {cp['name']} (Comunidad)",
                "description": cp.get("description", "Premio 5★ creado por la comunidad."),
                "rarity": 5,
                "creator_id": cp.get("creator_id")
            })
    catalog += list(THREE_STARS)
    return catalog

def find_item_details(item_name: str, custom_prizes: list = None):
    catalog = get_all_items_catalog(custom_prizes)
    clean_target = item_name.strip().lower()

    for it in catalog:
        if it["name"].strip().lower() == clean_target:
            return it

    for it in catalog:
        if clean_target in it["name"].lower():
            return it

    return None

